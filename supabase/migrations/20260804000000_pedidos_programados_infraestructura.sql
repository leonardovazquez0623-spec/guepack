-- 4. Reclamación segura de trabajos de asignación
-- ============================================================================

CREATE OR REPLACE FUNCTION public.reclamar_asignaciones_programadas(
  p_reclamado_por UUID,
  p_limite INTEGER DEFAULT 100,
  p_ahora TIMESTAMPTZ DEFAULT statement_timestamp()
)
RETURNS TABLE (
  outbox_id BIGINT,
  pedido_id BIGINT,
  tenant_id BIGINT,
  ronda INTEGER,
  intentos INTEGER
)
LANGUAGE plpgsql
VOLATILE
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_limite INTEGER;
BEGIN
  IF p_reclamado_por IS NULL THEN
    RAISE EXCEPTION USING
      ERRCODE = '22004', MESSAGE = 'RECLAMADO_POR_REQUERIDO';
  END IF;
  IF p_ahora IS NULL THEN
    RAISE EXCEPTION USING
      ERRCODE = '22004', MESSAGE = 'MOMENTO_ACTUAL_REQUERIDO';
  END IF;

  v_limite := LEAST(GREATEST(COALESCE(p_limite, 100), 1), 500);

  UPDATE public.pedidos_programados_outbox AS outbox
  SET
    estado = 'pendiente',
    reclamado_en = NULL,
    reclamado_por = NULL,
    actualizado_en = p_ahora
  WHERE outbox.estado = 'procesando'
    AND outbox.reclamado_en < p_ahora - INTERVAL '5 minutes';

  RETURN QUERY
  WITH candidatos AS (
    SELECT outbox.id
    FROM public.pedidos_programados_outbox AS outbox
    WHERE outbox.estado = 'pendiente'
    ORDER BY outbox.creado_en, outbox.id
    FOR UPDATE SKIP LOCKED
    LIMIT v_limite
  ),
  reclamados AS (
    UPDATE public.pedidos_programados_outbox AS outbox
    SET
      estado = 'procesando',
      intentos = outbox.intentos + 1,
      reclamado_en = p_ahora,
      reclamado_por = p_reclamado_por,
      actualizado_en = p_ahora,
      ultimo_error = NULL
    FROM candidatos
    WHERE outbox.id = candidatos.id
    RETURNING
      outbox.id,
      outbox.pedido_id,
      outbox.tenant_id,
      outbox.ronda,
      outbox.intentos
  )
  SELECT
    reclamados.id,
    reclamados.pedido_id,
    reclamados.tenant_id,
    reclamados.ronda,
    reclamados.intentos
  FROM reclamados
  ORDER BY reclamados.id;
END;
$function$;

REVOKE ALL ON FUNCTION public.reclamar_asignaciones_programadas(
  UUID, INTEGER, TIMESTAMPTZ
) FROM PUBLIC, anon, authenticated;

GRANT EXECUTE ON FUNCTION public.reclamar_asignaciones_programadas(
  UUID, INTEGER, TIMESTAMPTZ
) TO service_role;

-- ============================================================================
-- 5. Resolución de trabajos reclamados
-- ============================================================================

CREATE OR REPLACE FUNCTION public.resolver_asignacion_programada(
  p_outbox_id BIGINT,
  p_reclamado_por UUID,
  p_exitosa BOOLEAN,
  p_error TEXT DEFAULT NULL,
  p_ahora TIMESTAMPTZ DEFAULT statement_timestamp()
)
RETURNS BOOLEAN
LANGUAGE plpgsql
VOLATILE
SECURITY DEFINER
SET search_path TO ''
AS $function$
BEGIN
  IF p_outbox_id IS NULL
     OR p_reclamado_por IS NULL
     OR p_exitosa IS NULL
     OR p_ahora IS NULL THEN
    RAISE EXCEPTION USING
      ERRCODE = '22004', MESSAGE = 'PARAMETROS_DE_RESOLUCION_INCOMPLETOS';
  END IF;

  IF p_exitosa THEN
    UPDATE public.pedidos_programados_outbox AS outbox
    SET
      estado = 'procesado',
      procesado_en = p_ahora,
      actualizado_en = p_ahora,
      reclamado_en = NULL,
      reclamado_por = NULL,
      ultimo_error = NULL
    WHERE outbox.id = p_outbox_id
      AND outbox.estado = 'procesando'
      AND outbox.reclamado_por = p_reclamado_por;
  ELSE
    UPDATE public.pedidos_programados_outbox AS outbox
    SET
      estado = 'pendiente',
      actualizado_en = p_ahora,
      reclamado_en = NULL,
      reclamado_por = NULL,
      ultimo_error = left(coalesce(p_error, 'Error desconocido'), 2000)
    WHERE outbox.id = p_outbox_id
      AND outbox.estado = 'procesando'
      AND outbox.reclamado_por = p_reclamado_por;
  END IF;

  RETURN FOUND;
END;
$function$;

REVOKE ALL ON FUNCTION public.resolver_asignacion_programada(
  BIGINT, UUID, BOOLEAN, TEXT, TIMESTAMPTZ
) FROM PUBLIC, anon, authenticated;

GRANT EXECUTE ON FUNCTION public.resolver_asignacion_programada(
  BIGINT, UUID, BOOLEAN, TEXT, TIMESTAMPTZ
) TO service_role;

-- ============================================================================
-- 6. Defensa adicional: solo se acepta un pedido Pendiente
-- ============================================================================

CREATE OR REPLACE FUNCTION public.aceptar_pedido_atomico(p_pedido_id BIGINT)
RETURNS INTEGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
  usuario_id UUID;
  repartidor_nombre TEXT;
  repartidor_tenant_id BIGINT;
  ganancia_base_config NUMERIC;
  ganancia_por_km_config NUMERIC;
  ganancia_diaria_config NUMERIC;
  pedido_tenant_id BIGINT;
  pedido_repartidor TEXT;
  pedido_estado TEXT;
  pedido_km NUMERIC;
  pedido_precio NUMERIC;
  pedido_zona TEXT;
  ganancia_calculada NUMERIC;
  filas_afectadas INTEGER;
BEGIN
  usuario_id := auth.uid();
  IF usuario_id IS NULL THEN
    RAISE EXCEPTION 'Se requiere una sesión autenticada'
      USING ERRCODE = '28000';
  END IF;

  SELECT
    r.nombre,
    r.tenant_id,
    COALESCE(r.ganancia_base, 20),
    COALESCE(r.ganancia_por_km, 5),
    COALESCE(r.ganancia_tarifa_diaria, 40)
  INTO
    repartidor_nombre,
    repartidor_tenant_id,
    ganancia_base_config,
    ganancia_por_km_config,
    ganancia_diaria_config
  FROM public.usuarios AS u
  INNER JOIN public.repartidores AS r
    ON LOWER(r.email) = LOWER(u.email)
   AND r.tenant_id = u.tenant_id
  WHERE u.user_id = usuario_id::TEXT
    AND u.rol = 'repartidor'
    AND r.disponible IS TRUE
  LIMIT 1;

  IF repartidor_nombre IS NULL THEN
    RAISE EXCEPTION
      'El usuario autenticado no corresponde a un repartidor disponible'
      USING ERRCODE = '42501';
  END IF;

  SELECT
    p.tenant_id,
    p.repartidor,
    p.estado,
    COALESCE(p.km_recorridos, 0),
    COALESCE(p.precio, 0),
    COALESCE(p.zona, '')
  INTO
    pedido_tenant_id,
    pedido_repartidor,
    pedido_estado,
    pedido_km,
    pedido_precio,
    pedido_zona
  FROM public.pedidos AS p
  WHERE p.id = p_pedido_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'El pedido solicitado no existe'
      USING ERRCODE = 'P0002';
  END IF;
  IF pedido_tenant_id IS DISTINCT FROM repartidor_tenant_id THEN
    RAISE EXCEPTION 'El repartidor no pertenece al tenant del pedido'
      USING ERRCODE = '42501';
  END IF;
  IF pedido_estado IS DISTINCT FROM 'Pendiente' THEN
    RETURN 0;
  END IF;
  IF pedido_repartidor IS NOT NULL THEN
    RETURN 0;
  END IF;

  IF pedido_zona ILIKE '%Tarifa diaria%' THEN
    ganancia_calculada := ROUND(
      pedido_precio * ganancia_diaria_config / 100
    );
  ELSE
    ganancia_calculada := ROUND(
      ganancia_base_config + pedido_km * ganancia_por_km_config
    );
  END IF;

  UPDATE public.pedidos
  SET
    repartidor = repartidor_nombre,
    asignacion_automatica = TRUE,
    ganancia_repartidor = ganancia_calculada
  WHERE id = p_pedido_id
    AND repartidor IS NULL
    AND estado = 'Pendiente';

  GET DIAGNOSTICS filas_afectadas = ROW_COUNT;
  RETURN filas_afectadas;
END;
$function$;

REVOKE ALL ON FUNCTION public.aceptar_pedido_atomico(BIGINT)
FROM PUBLIC, anon;

GRANT EXECUTE ON FUNCTION public.aceptar_pedido_atomico(BIGINT)
TO authenticated;

-- ============================================================================
-- 7. Cron cada minuto usando el secreto existente de Vault
-- ============================================================================

DO $cron_setup$
DECLARE
  v_service_role_key_existe BOOLEAN;
  v_job_id BIGINT;
BEGIN
  SELECT EXISTS (
    SELECT 1
    FROM vault.secrets AS secreto
    WHERE secreto.name = 'cron_service_role_key'
  )
  INTO v_service_role_key_existe;

  IF NOT v_service_role_key_existe THEN
    RAISE EXCEPTION USING
      ERRCODE = '22023',
      MESSAGE = 'VAULT_CRON_SERVICE_ROLE_KEY_FALTANTE',
      HINT = 'El secreto cron_service_role_key debe existir en Vault.';
  END IF;

  SELECT trabajo.jobid
  INTO v_job_id
  FROM cron.job AS trabajo
  WHERE trabajo.jobname = 'activar-pedidos-programados-cada-minuto'
  LIMIT 1;

  IF v_job_id IS NOT NULL THEN
    PERFORM cron.unschedule(v_job_id);
  END IF;

  PERFORM cron.schedule(
    'activar-pedidos-programados-cada-minuto',
    '* * * * *',
    $job$
    SELECT net.http_post(
      url := 'https://zkrnjdsnuyjaxxnluzmn.supabase.co/functions/v1/activar-pedidos-programados',
      headers := jsonb_build_object(
        'Content-Type', 'application/json',
        'Authorization',
        'Bearer ' || (
          SELECT secreto.decrypted_secret
          FROM vault.decrypted_secrets AS secreto
          WHERE secreto.name = 'cron_service_role_key'
          ORDER BY secreto.created_at DESC
          LIMIT 1
        )
      ),
      body := '{}'::jsonb
    );
    $job$
  );
END;
$cron_setup$;

COMMIT;
