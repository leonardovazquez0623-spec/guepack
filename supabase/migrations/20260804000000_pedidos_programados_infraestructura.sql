CREATE TABLE IF NOT EXISTS public.pedidos_programados_outbox (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pedido_id BIGINT NOT NULL,
  tenant_id BIGINT NOT NULL,
  ronda INTEGER NOT NULL DEFAULT 1,
  estado TEXT NOT NULL DEFAULT 'pendiente',
  intentos INTEGER NOT NULL DEFAULT 0,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
  procesado_en TIMESTAMPTZ,
  reclamado_en TIMESTAMPTZ,
  reclamado_por UUID,
  ultimo_error TEXT,
  CONSTRAINT pedidos_programados_outbox_pedido_key UNIQUE (pedido_id),
  CONSTRAINT pedidos_programados_outbox_pedido_fk
    FOREIGN KEY (pedido_id) REFERENCES public.pedidos(id) ON DELETE CASCADE,
  CONSTRAINT pedidos_programados_outbox_tenant_fk
    FOREIGN KEY (tenant_id) REFERENCES public.tenants(id) ON DELETE CASCADE,
  CONSTRAINT pedidos_programados_outbox_estado_chk
    CHECK (estado IN ('pendiente', 'procesando', 'procesado')),
  CONSTRAINT pedidos_programados_outbox_ronda_chk CHECK (ronda > 0),
  CONSTRAINT pedidos_programados_outbox_intentos_chk CHECK (intentos >= 0)
);

