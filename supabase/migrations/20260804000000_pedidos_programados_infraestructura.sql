-- ============================================================================
-- 3. Evaluación y activación atómica del lote
-- ============================================================================

CREATE OR REPLACE FUNCTION public.activar_pedidos_programados_lote(
  p_limite INTEGER DEFAULT 100,
  p_ahora TIMESTAMPTZ DEFAULT statement_timestamp()
)
RETURNS JSONB
LANGUAGE plpgsql
VOLATILE
SECURITY DEFINER
SET search_path TO ''
AS $function$
DECLARE
  v_lock_obtenido BOOLEAN;
  v_limite INTEGER;
  v_evaluados INTEGER := 0;
  v_activados INTEGER := 0;
  v_configuraciones_invalidas INTEGER := 0;
  v_fechas_invalidas INTEGER := 0;
  v_pedidos_activados JSONB := '[]'::JSONB;
  v_incidencias JSONB := '[]'::JSONB;
  v_alerta_nueva BOOLEAN;
  v_fecha_alerta DATE;
  v_registro RECORD;
BEGIN
  IF p_ahora IS NULL THEN
    RAISE EXCEPTION USING
      ERRCODE = '22004',
      MESSAGE = 'MOMENTO_ACTUAL_REQUERIDO';
  END IF;

  v_limite := LEAST(GREATEST(COALESCE(p_limite, 100), 1), 500);

  v_lock_obtenido :=
    pg_catalog.pg_try_advisory_xact_lock(
      pg_catalog.hashtextextended('activar_pedidos_programados', 0)
    );

  IF NOT v_lock_obtenido THEN
    RETURN jsonb_build_object(
      'success', TRUE,
      'omitido_por_ejecucion_en_curso', TRUE,
      'evaluados', 0,
      'activados', 0,
      'configuraciones_invalidas', 0,
      'fechas_invalidas', 0,
      'pedidos_activados', '[]'::JSONB,
      'incidencias', '[]'::JSONB
    );
  END IF;

  SELECT count(*)
  INTO v_evaluados
  FROM public.pedidos AS pedido
  WHERE pedido.estado = 'Programado';

  FOR v_registro IN
    SELECT pedido.id AS pedido_id, pedido.tenant_id, pedido.fecha
    FROM public.pedidos AS pedido
    WHERE pedido.estado = 'Programado'
      AND (
        pedido.fecha IS NULL
        OR pedido.fecha !~ '^\d{4}-\d{2}-\d{2}$'
        OR to_char(to_date(pedido.fecha, 'YYYY-MM-DD'), 'YYYY-MM-DD')
          <> pedido.fecha
      )
    ORDER BY pedido.id
    LIMIT v_limite
  LOOP
    v_fechas_invalidas := v_fechas_invalidas + 1;
    RAISE LOG
      'PEDIDO_PROGRAMADO_FECHA_INVALIDA pedido_id=% tenant_id=% fecha=%',
      v_registro.pedido_id,
      v_registro.tenant_id,
      coalesce(v_registro.fecha, 'NULL');
  END LOOP;

  FOR v_registro IN
    SELECT
      pedido.id AS pedido_id,
      pedido.tenant_id,
      tenant.zona_horaria,
      configuracion.tenant_id AS configuracion_tenant_id,
      configuracion.horario_apertura,
      CASE
        WHEN configuracion.tenant_id IS NULL
          THEN 'CONFIGURACION_FALTANTE'
        WHEN configuracion.horario_apertura IS NULL
          THEN 'HORARIO_APERTURA_FALTANTE'
        WHEN tenant.zona_horaria IS NULL
          THEN 'ZONA_HORARIA_FALTANTE'
      END AS motivo
    FROM public.pedidos AS pedido
    LEFT JOIN public.tenants AS tenant ON tenant.id = pedido.tenant_id
    LEFT JOIN public.configuracion AS configuracion
      ON configuracion.tenant_id = pedido.tenant_id
    WHERE pedido.estado = 'Programado'
      AND (
        configuracion.tenant_id IS NULL
        OR configuracion.horario_apertura IS NULL
        OR tenant.zona_horaria IS NULL
      )
    ORDER BY pedido.id
    LIMIT v_limite
  LOOP
    v_configuraciones_invalidas := v_configuraciones_invalidas + 1;
    RAISE LOG
      'PEDIDO_PROGRAMADO_CONFIGURACION_INVALIDA pedido_id=% tenant_id=% motivo=%',
      v_registro.pedido_id,
      v_registro.tenant_id,
      v_registro.motivo;

    v_fecha_alerta :=
      (p_ahora AT TIME ZONE coalesce(v_registro.zona_horaria, 'UTC'))::DATE;
    v_alerta_nueva := FALSE;

    INSERT INTO public.alertas_configuracion_log (
      pedido_id, tenant_id, fecha_dia, motivo, enviado_en
    )
    VALUES (
      v_registro.pedido_id,
      v_registro.tenant_id,
      v_fecha_alerta,
      v_registro.motivo,
      p_ahora
    )
    ON CONFLICT ON CONSTRAINT alertas_configuracion_log_pedido_fecha_key
    DO NOTHING
    RETURNING TRUE INTO v_alerta_nueva;

    v_incidencias := v_incidencias || jsonb_build_array(
      jsonb_build_object(
        'pedido_id', v_registro.pedido_id,
        'tenant_id', v_registro.tenant_id,
        'motivo', v_registro.motivo,
        'debe_enviar_alerta', coalesce(v_alerta_nueva, FALSE)
      )
    );
  END LOOP;

  FOR v_registro IN
    SELECT
      pedido.id AS pedido_id,
      pedido.tenant_id,
      pedido.metodo_pago,
      pedido.pago_verificado,
      pedido.fecha,
      configuracion.horario_apertura,
      tenant.zona_horaria
    FROM public.pedidos AS pedido
    INNER JOIN public.tenants AS tenant ON tenant.id = pedido.tenant_id
    INNER JOIN public.configuracion AS configuracion
      ON configuracion.tenant_id = pedido.tenant_id
    WHERE pedido.estado = 'Programado'
      AND pedido.repartidor IS NULL
      AND pedido.fecha ~ '^\d{4}-\d{2}-\d{2}$'
      AND to_char(to_date(pedido.fecha, 'YYYY-MM-DD'), 'YYYY-MM-DD')
        = pedido.fecha
      AND configuracion.horario_apertura IS NOT NULL
      AND tenant.zona_horaria IS NOT NULL
      AND p_ahora >= (
        (
          to_date(pedido.fecha, 'YYYY-MM-DD')
          + configuracion.horario_apertura
        ) AT TIME ZONE tenant.zona_horaria
      )
      AND (
        lower(btrim(coalesce(pedido.metodo_pago, '')))
          NOT IN ('tarjeta', 'transferencia')
        OR pedido.pago_verificado IS TRUE
      )
    ORDER BY pedido.id
    FOR UPDATE OF pedido SKIP LOCKED
    LIMIT v_limite
  LOOP
    UPDATE public.pedidos AS pedido
    SET estado = 'Pendiente', ronda_asignacion = 0
    WHERE pedido.id = v_registro.pedido_id
      AND pedido.estado = 'Programado'
      AND pedido.repartidor IS NULL;

    IF NOT FOUND THEN
      CONTINUE;
    END IF;

    INSERT INTO public.pedidos_programados_outbox (
      pedido_id, tenant_id, ronda, estado, creado_en, actualizado_en
    )
    VALUES (
      v_registro.pedido_id,
      v_registro.tenant_id,
      1,
      'pendiente',
      p_ahora,
      p_ahora
    )
    ON CONFLICT ON CONSTRAINT pedidos_programados_outbox_pedido_key
    DO NOTHING;

    v_activados := v_activados + 1;
    v_pedidos_activados := v_pedidos_activados || jsonb_build_array(
      jsonb_build_object(
        'pedido_id', v_registro.pedido_id,
        'tenant_id', v_registro.tenant_id,
        'estado', 'Pendiente'
      )
    );
  END LOOP;

  RETURN jsonb_build_object(
    'success', TRUE,
    'omitido_por_ejecucion_en_curso', FALSE,
    'evaluados', v_evaluados,
    'activados', v_activados,
    'configuraciones_invalidas', v_configuraciones_invalidas,
    'fechas_invalidas', v_fechas_invalidas,
    'pedidos_activados', v_pedidos_activados,
    'incidencias', v_incidencias
  );
END;
$function$;

REVOKE ALL ON FUNCTION public.activar_pedidos_programados_lote(
  INTEGER, TIMESTAMPTZ
) FROM PUBLIC, anon, authenticated;

GRANT EXECUTE ON FUNCTION public.activar_pedidos_programados_lote(
  INTEGER, TIMESTAMPTZ
) TO service_role;

